// Builds the Luno-style icon components and a preview sheet from icons.spec.mjs.
// usage (repo root): node .claude/skills/luno-icons/make-icons.mjs
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ICONS } from './icons.spec.mjs';

const OUT = join(process.cwd(), 'admin/src/components/icons/luno');
const PREVIEW = join(process.cwd(), 'logs/qa/redesign/icon-preview.html');
const STROKE = 1.15;

const toneAttrs = (tone, jsx) => {
  const accent = 'var(--icon-accent, var(--secondary))';
  if (tone === 'accentFill') return jsx ? `fill="${accent}" stroke="none"` : `fill="${accent}" stroke="none"`;
  if (tone === 'accent') return `stroke="${accent}"`;
  return '';
};

function shape(s, jsx) {
  const [kind, ...a] = s;
  const tone = typeof a[a.length - 1] === 'string' && /^(base|accent|accentFill)$/.test(a[a.length - 1]) ? a.pop() : 'base';
  const t = toneAttrs(tone, jsx);
  if (kind === 'path') return `<path d="${a[0]}" ${t}/>`;
  if (kind === 'rect') return `<rect x="${a[0]}" y="${a[1]}" width="${a[2]}" height="${a[3]}" rx="${a[4] ?? 0}" ${t}/>`;
  if (kind === 'circle') return `<circle cx="${a[0]}" cy="${a[1]}" r="${a[2]}" ${t}/>`;
  if (kind === 'line') return `<line x1="${a[0]}" y1="${a[1]}" x2="${a[2]}" y2="${a[3]}" ${t}/>`;
  throw new Error(`unknown shape ${kind}`);
}

const inner = (shapes, jsx) => shapes.map((s) => shape(s, jsx)).join('');

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const names = Object.keys(ICONS).sort();
for (const name of names) {
  writeFileSync(
    join(OUT, `${name}.tsx`),
    `// Generated by .claude/skills/luno-icons/make-icons.mjs — edit icons.spec.mjs, not this file.
import type { SVGProps } from 'react'

const Luno${name} = (props: SVGProps<SVGSVGElement>) => (
  <svg viewBox='0 0 16 16' width={18} height={18} fill='none' stroke='currentColor' strokeWidth={${STROKE}} strokeLinecap='round' strokeLinejoin='round' aria-hidden {...props}>
    ${inner(ICONS[name], true).replaceAll('"', "'")}
  </svg>
)

export default Luno${name}
`
  );
}
writeFileSync(join(OUT, 'index.ts'), `// Generated by .claude/skills/luno-icons/make-icons.mjs.\n${names.map((n) => `export { default as Luno${n} } from './${n}'`).join('\n')}\n`);

const svg = (name, size) => `<svg viewBox="0 0 16 16" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">${inner(ICONS[name], false)}</svg>`;
const sheet = (theme) => `<section class="${theme}"><h2>${theme}</h2><div class="grid">${names.map((n) => `<figure>${svg(n, 96)}<div class="row">${svg(n, 26)}${svg(n, 18)}</div><figcaption>${n}</figcaption></figure>`).join('')}</div></section>`;
mkdirSync(join(PREVIEW, '..'), { recursive: true });
writeFileSync(PREVIEW, `<!doctype html><meta charset="utf-8"><title>Luno icons</title><style>
body{margin:0;font:14px Nunito,system-ui,sans-serif}
section{padding:24px}.light{background:#f4f7f6;color:#363535;--secondary:#00ac9a}.dark{background:#1d1f22;color:#e0e0e0;--secondary:#00ac9a}
.grid{display:grid;grid-template-columns:repeat(auto-fill,140px);gap:16px}
figure{margin:0;background:var(--card,#fff);border:1px dashed #e9e6e1;border-radius:12px;padding:12px;display:flex;flex-direction:column;align-items:center;gap:8px}
.dark figure{--card:#25272b;border-color:#3a3d42}.row{display:flex;gap:12px;align-items:center}figcaption{font-size:12px}
</style>${sheet('light')}${sheet('dark')}`);
console.log(`${names.length} icons → ${OUT.replace(process.cwd() + '/', '')}, preview ${PREVIEW.replace(process.cwd() + '/', '')}`);
